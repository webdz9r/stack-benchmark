#!/usr/bin/env python3
"""Generate src/unicode_table.h: code point ranges whose Unicode general category
is a Letter, Mark or Number (L*, M*, N*), the search word characters of
docs/requirements/02-database.md §6.2 (DB-12).

    python3 scripts/gen_unicode.py > src/unicode_table.h
"""
import sys
import unicodedata

ranges = []
start = None
for cp in range(sys.maxunicode + 1):
    word = unicodedata.category(chr(cp))[0] in "LMN"
    if word and start is None:
        start = cp
    elif not word and start is not None:
        ranges.append((start, cp - 1))
        start = None
if start is not None:
    ranges.append((start, sys.maxunicode))

print(f"/* Generated by scripts/gen_unicode.py from Unicode {unicodedata.unidata_version}. Do not edit. */")
print("/* Code point ranges with general category L*, M* or N* (sorted, inclusive). */")
print(f"static const unsigned int WORD_RANGES[{len(ranges)}][2] = {{")
for a, b in ranges:
    print(f"    {{0x{a:X}, 0x{b:X}}},")
print("};")
